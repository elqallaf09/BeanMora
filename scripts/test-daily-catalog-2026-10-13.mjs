import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileCatalog } from './prepare-roaster-recipes.mjs';
const read = name => JSON.parse(readFileSync(new URL(`../supabase/research/daily-2026-10-13/${name}`, import.meta.url), 'utf8'));
test('cold bottle recipe preserves an upper time bound, unknown temperature and reusable identity', () => {
  const catalog = compileCatalog({ ...read('input.json'), snapshot: read('public-catalog-snapshot.json') });
  assert.deepEqual(catalog, read('catalog.json'));
  assert.equal(catalog.counts.new_recipes, 1);
  assert.equal(catalog.counts.roaster_actions.create, 2);
  assert.equal(catalog.counts.roaster_actions.reuse_exact, 1);
  const recipe = catalog.recipes[0];
  assert.equal(recipe.serving_style, 'cold');
  assert.equal(recipe.brew_method, 'cold_brew');
  assert.equal(recipe.dose_grams, 68);
  assert.equal(recipe.water_grams, 750);
  assert.equal(recipe.water_temp_c, null);
  assert.equal(recipe.water_temp_c_min, null);
  assert.equal(recipe.total_time_seconds, null);
  assert.equal(recipe.source_brew_parameters.manual.steep_duration_upper_seconds, 64800);
  assert.equal(recipe.source_brew_parameters.manual.time_min_seconds, undefined);
  assert.equal(recipe.is_incomplete_source, true);
  assert.equal(recipe.coffee_key, null);
  assert.equal(recipe.cover_image_url, null);
  assert.equal(recipe.pours.reduce((sum, row) => sum + row.water_grams, 0), 750);
  assert(recipe.steps.every(row => row.description && row.description_ar));
  assert.deepEqual(catalog.roasters.filter(row => row.action === 'create').map(row => row.country), ['SA', 'AE']);
  const sql = readFileSync(new URL('../supabase/research/daily-2026-10-13/import.sql', import.meta.url), 'utf8');
  assert(sql.includes('Existing catalog records changed'));
  assert(sql.includes('Recipe owner/method conflict'));
});
