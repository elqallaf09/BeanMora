import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compileCatalog} from './prepare-roaster-recipes.mjs';
const read=name=>JSON.parse(readFileSync(new URL('../supabase/research/daily-2026-10-15/'+name,import.meta.url),'utf8'));
test('reviewed Kuwait/Kalita batch preserves unspecified units and avoids invented pours',()=>{
  const compiled=compileCatalog({...read('input.json'),snapshot:read('public-catalog-snapshot.json')});
  assert.deepEqual(compiled,read('catalog.json'));
  assert.equal(compiled.counts.new_recipes,1);
  assert.equal(compiled.counts.roaster_actions.create,2);
  assert(compiled.roasters.every(r=>r.country==='KW'));
  const recipe=compiled.recipes[0];
  assert.equal(recipe.dose_grams,20);
  assert.equal(recipe.water_grams,320);
  assert.equal(recipe.water_temp_c,null);
  assert.equal(recipe.total_time_seconds,null);
  assert.equal(recipe.serving_style,'unknown');
  assert.equal(recipe.recipe_type,'official_manufacturer');
  assert.equal(recipe.roaster_key,null);
  assert.equal(recipe.cover_image_url,null);
  assert.equal(recipe.source_brew_parameters.manual.time_min_seconds,120);
  assert.equal(recipe.source_brew_parameters.manual.time_max_seconds,180);
  assert.equal(recipe.source_brew_parameters.manual.source_ratio_text,'1:16');
  assert.equal(recipe.pours.length,0);
  assert.equal(recipe.steps.length,5);
  const sql=readFileSync(new URL('../supabase/research/daily-2026-10-15/import.sql',import.meta.url),'utf8');
  assert(sql.includes('Existing catalog records changed'));
  const correction=readFileSync(new URL('../supabase/research/daily-2026-10-15/correct-harenna-temperature.sql',import.meta.url),'utf8');
  assert(correction.includes('beanmora_official'));
  assert(correction.includes('Source step changed; refusing correction'));
  assert(correction.includes('Unrelated steps changed'));
});
